import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const scannerBin = readFileSync(resolve(root, "system/unix/build/scanner.bin"));
const genPath = resolve(root, "src/game/scanner-generated.js");

const content = `// Generated by scripts/generate-scanner-media.mjs — scanner binary for in-game computer
export const SCANNER_ASM = "";
export const SCANNER_BIN = new Uint8Array(${JSON.stringify(Array.from(scannerBin))});
`;

writeFileSync(genPath, content);
console.log(`Generated scanner-generated.js (${scannerBin.length} bytes)`);