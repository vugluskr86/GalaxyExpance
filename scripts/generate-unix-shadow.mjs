import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const target=path.join(root,"system","unix","etc","shadow");
const check=process.argv.includes("--check");
const encoder=new TextEncoder();

function fnv(bytes){
  let hash=0x811c9dc5;
  for(const byte of bytes)hash=Math.imul((hash^byte)>>>0,0x01000193)>>>0;
  return hash>>>0;
}
function passwordHash(password,salt){
  let state=fnv(encoder.encode(salt+password));
  const word=new Uint8Array(4),view=new DataView(word.buffer);
  for(let round=0;round<1024;round++){
    view.setUint32(0,state,true);
    state=fnv(word);
  }
  return `0x${state.toString(16).padStart(8,"0")}`;
}

const accounts=[
  ["root","root","rootsalt"],
  ["guest","guest","guestslt"],
];
const content=[
  "; Generated by scripts/generate-unix-shadow.mjs; game credentials only.",
  ...accounts.map(([name,password,salt])=>`${name}:${passwordHash(password,salt)}:${salt}`),
  "",
].join("\n");
const old=fs.existsSync(target)?fs.readFileSync(target,"utf8"):null;
if(check){
  if(old!==content){
    console.error("Unix shadow template is stale; run node scripts/generate-unix-shadow.mjs");
    process.exit(1);
  }
  console.log("OK: Unix shadow template is current");
}else{
  fs.mkdirSync(path.dirname(target),{recursive:true});
  fs.writeFileSync(target,content);
  console.log("OK: generated game-only root and guest password hashes");
}
