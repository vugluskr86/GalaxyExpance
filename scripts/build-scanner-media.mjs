/** Build the standalone PCFD disk for the native PCOS scanner application.
 *
 * The disk intentionally contains the exact executable, C source, generated
 * Assembly, public ABI header and operator documentation.  It is separate
 * from the OS installer so a player/developer can inspect and run the scanner
 * without treating a hidden JavaScript scene as the application. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const build=path.join(root,"system","unix","build"),check=process.argv.includes("--check"),encoder=new TextEncoder();
const hash=bytes=>{let value=0x811c9dc5;for(const byte of bytes){value^=byte;value=Math.imul(value,0x01000193);}return value>>>0;};
const read=relative=>new Uint8Array(fs.readFileSync(path.join(root,relative)));
const required=["system/unix/build/scanner.bin","system/unix/build/scanner.asm","examples/c/scanner.c","libc/include/pcos.h","documentation/toolchain/SCANNER_C_IMPLEMENTATION.md","documentation/gameplay/SCANNER_AND_ECONOMY.md"];
for(const relative of required)if(!fs.existsSync(path.join(root,relative)))throw new Error(`Scanner media input is missing: ${relative}`);

const files=[
  ["system/unix/build/scanner.bin","/usr/bin/scanner.bin",0o755],
  ["examples/c/scanner.c","/usr/src/pcos-scanner/scanner.c",0o644],
  ["system/unix/build/scanner.asm","/usr/src/pcos-scanner/build/scanner.asm",0o644],
  ["libc/include/pcos.h","/usr/include/pcos.h",0o644],
  ["documentation/toolchain/SCANNER_C_IMPLEMENTATION.md","/usr/share/doc/pcos-scanner/BUILD.md",0o644],
  ["documentation/gameplay/SCANNER_AND_ECONOMY.md","/usr/share/doc/pcos-scanner/INTEGRATION.md",0o644]
].map(([source,target,mode])=>({path:target,data:read(source),uid:0,gid:0,mode,source}));
const directories=["/usr","/usr/bin","/usr/include","/usr/src","/usr/src/pcos-scanner","/usr/src/pcos-scanner/build","/usr/share","/usr/share/doc","/usr/share/doc/pcos-scanner"];
files.sort((a,b)=>a.path.localeCompare(b.path));
const total=9+files.reduce((sum,file)=>sum+2+encoder.encode(file.path).length+20+file.data.length,0);
const image=new Uint8Array(total),view=new DataView(image.buffer);image.set(encoder.encode("PCFD"));view.setUint8(4,1);view.setUint32(5,files.length,true);let at=9;
for(const file of files){
  const name=encoder.encode(file.path);view.setUint16(at,name.length,true);at+=2;image.set(name,at);at+=name.length;
  view.setUint32(at,file.uid,true);view.setUint32(at+4,file.gid,true);view.setUint32(at+8,file.mode,true);view.setUint32(at+12,file.data.length,true);view.setUint32(at+16,hash(file.data),true);at+=20;image.set(file.data,at);at+=file.data.length;
}
const manifest={format:"PCFD",version:1,label:"PCOS Scanner Native Source Disk",compiler:"PCVM native C compiler",entry:"/usr/bin/scanner.bin",directories,entries:files.map(file=>({path:file.path,source:file.source,size:file.data.length,checksum:hash(file.data),mode:file.mode}))};
const outputs=[
  [path.join(build,"scanner.pcfd"),Buffer.from(image)],
  [path.join(build,"scanner.manifest.json"),Buffer.from(JSON.stringify(manifest,null,2)+"\n")],
  [path.join(root,"src","game","scanner-media.generated.js"),Buffer.from(`// Generated by scripts/build-scanner-media.mjs.\nexport const SCANNER_MEDIA_MANIFEST=${JSON.stringify(manifest)};\nexport const SCANNER_PCFD_BASE64=${JSON.stringify(Buffer.from(image).toString("base64"))};\n`)]
];
let stale=false;for(const [file,data] of outputs){const old=fs.existsSync(file)?fs.readFileSync(file):null;if(!old||Buffer.compare(old,data)!==0)stale=true;}
if(check&&stale){console.error("Scanner PCFD media is stale; run node scripts/build-scanner-media.mjs");process.exit(1);}
if(!check)for(const [file,data] of outputs){fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,data);}
console.log(check?"OK: scanner PCFD media is current":`OK: built scanner PCFD (${image.length} bytes, ${files.length} files)`);
