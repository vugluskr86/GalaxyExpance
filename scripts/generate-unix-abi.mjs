#!/usr/bin/env node
/** Генератор Assembly .inc файлов из нормативного JS ABI.
 *  Usage:
 *    node scripts/generate-unix-abi.mjs           — записать include файлы
 *    node scripts/generate-unix-abi.mjs --check   — проверить, что файлы свежие (exit≠0 если нет)
 *  Всегда читает src/game/protected-mode.js как единственный источник истины.
 *  Не принимает внешних аргументов кроме --check.
 *  Идемпотентен: повторный запуск даёт тот же результат.
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { resolve, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const workspaceRoot = resolve(__dirname, "..");
const targetDir = resolve(workspaceRoot, "system", "unix", "include");
const sourceModule = resolve(workspaceRoot, "src", "game", "protected-mode.js");

const HEADER = [
  "; Auto-generated from src/game/protected-mode.js — do not edit manually.",
  "; Единый нормативный источник syscall/errno/struct констант.",
  "; Generated by: node scripts/generate-unix-abi.mjs",
  "",
].join("\n");

const SPLIT_HEADERS = {
  "syscall.inc":    "; Auto-generated syscall numbers — do not edit manually.",
  "limits.inc":     "; Auto-generated ABI limits — do not edit manually.",
  "errno.inc":      "; Auto-generated errno codes — do not edit manually.",
  "open_flags.inc": "; Auto-generated open flags — do not edit manually.",
  "seek.inc":       "; Auto-generated seek whence — do not edit manually.",
  "inode.inc":      "; Auto-generated inode types — do not edit manually.",
  "process.inc":    "; Auto-generated process states — do not edit manually.",
  "structs.inc":    "; Auto-generated struct layouts — do not edit manually.",
  "protected.inc":  "; Auto-generated protected mode constants — do not edit manually.",
};

const SPLIT_MARKERS = [
  { marker: "=== Syscall numbers (PCVM v3) ===", file: "syscall.inc" },
  { marker: "=== Limits ===",                      file: "limits.inc" },
  { marker: "=== Errno ===",                        file: "errno.inc" },
  { marker: "=== Open flags ===",                   file: "open_flags.inc" },
  { marker: "=== Seek whence ===",                  file: "seek.inc" },
  { marker: "=== Inode types ===",                  file: "inode.inc" },
  { marker: "=== Process states ===",               file: "process.inc" },
  { marker: "=== Struct layouts",                   file: "structs.inc" },
  { marker: "=== Protected mode constants ===",     file: "protected.inc" },
];

function splitContent(content) {
  const lines = content.split("\n");
  const files = {};
  let currentFile = null;

  for (const line of lines) {
    for (const { marker, file } of SPLIT_MARKERS) {
      if (line.startsWith(`; ${marker}`)) {
        currentFile = file;
        if (!files[currentFile]) files[currentFile] = [];
        break;
      }
    }
    if (currentFile && files[currentFile]) {
      files[currentFile].push(line);
    }
  }

  return files;
}

function generate(requireFn) {
  const mod = requireFn(sourceModule);

  if (typeof mod.generateAssemblyConstants !== "function") {
    throw new Error("protected-mode.js должен экспортировать generateAssemblyConstants()");
  }

  const rawContent = mod.generateAssemblyConstants();
  const content = HEADER + rawContent;

  const files = {
    "abi.inc": content,
  };

  const split = splitContent(content);
  for (const [name, lines] of Object.entries(split)) {
    const header = SPLIT_HEADERS[name] || "";
    files[name] = header + "\n" + lines.join("\n").trim() + "\n";
  }

  return files;
}

function writeFiles(files) {
  mkdirSync(targetDir, { recursive: true });
  let written = 0;
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(join(targetDir, name), content, "utf-8");
    written++;
  }
  return written;
}

function checkFiles(generated) {
  const errors = [];
  for (const [name, expectedContent] of Object.entries(generated)) {
    const path = join(targetDir, name);
    let actual;
    try {
      actual = readFileSync(path, "utf-8");
    } catch {
      errors.push(`MISSING: ${name}`);
      continue;
    }
    if (actual !== expectedContent) {
      errors.push(`OUTDATED: ${name} (содержимое не соответствует сгенерированному)`);
    }
  }

  // Check for extra files not in generated set
  try {
    const existing = readdirSync(targetDir);
    for (const name of existing) {
      if (!generated[name]) {
        errors.push(`EXTRA: ${name} (не генерируется скриптом)`);
      }
    }
  } catch {
    // directory doesn't exist yet
  }

  return errors;
}

// --- MAIN ---
const checkMode = process.argv.includes("--check");

// Use createRequire to load ESM module from workspace root
const requireFn = createRequire(join(workspaceRoot, "noop.js"));

let generated;
try {
  generated = generate(requireFn);
} catch (err) {
  console.error(`ERROR: ${err.message}`);
  process.exit(2);
}

if (checkMode) {
  const errors = checkFiles(generated);
  if (errors.length > 0) {
    console.error("ABI include files are not up-to-date:");
    for (const err of errors) console.error(`  - ${err}`);
    console.error("Run: node scripts/generate-unix-abi.mjs");
    process.exit(1);
  }
  console.log(`OK: ${Object.keys(generated).length} include files are up-to-date.`);
  process.exit(0);
}

const count = writeFiles(generated);
const names = Object.keys(generated).sort().join(", ");
console.log(`OK: wrote ${count} files to ${relative(workspaceRoot, targetDir)} (${names})`);