import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {Assembler} from "../src/game/cpu.js";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const unix=path.join(root,"system","unix"),build=path.join(unix,"build");
const check=process.argv.includes("--check"),encoder=new TextEncoder();
const hash=bytes=>{let value=0x811c9dc5;for(const byte of bytes){value^=byte;value=Math.imul(value,0x01000193);}return value>>>0;};
const entries=[],seen=new Set();
function add(source,target,meta={}){
  if(seen.has(target))return;seen.add(target);
  const data=new Uint8Array(fs.readFileSync(source));
  entries.push({path:target,data,uid:meta.uid??0,gid:meta.gid??0,mode:parseInt(String(meta.mode??"0644"),8),checksum:hash(data)});
}
function walk(dir,prefix){
  for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
    if(entry.name==="build")continue;
    const full=path.join(dir,entry.name),target=`${prefix}/${entry.name}`;
    if(entry.isDirectory())walk(full,target);else if(entry.isFile())add(full,target);
  }
}
const manifest=JSON.parse(fs.readFileSync(path.join(unix,"install-manifest.json"),"utf8"));
for(const entry of manifest.files)add(path.join(unix,entry.source),entry.path,entry);
add(path.join(build,"kernel.bin"),"/kernel.bin",{mode:"0755"});
for(const name of fs.readdirSync(build))if(/\.bin$/i.test(name))
  add(path.join(build,name),`/usr/src/pcos/system/unix/build/${name}`);
walk(path.join(unix),"/usr/src/pcos/system/unix");
add(path.join(root,"system","assembler.asm"),"/usr/src/pcos/system/assembler.asm");
add(path.join(root,"system","linker.asm"),"/usr/src/pcos/system/linker.asm");
const installConf=encoder.encode("unattended=true\nroot_password=root\nguest=true\nboot_file=kernel.bin\n");
entries.push({path:"/install.conf",data:installConf,uid:0,gid:0,mode:0o600,checksum:hash(installConf)});
const directoryManifest=encoder.encode(JSON.stringify(manifest.directories));
entries.push({path:"/.pcfd-directories.json",data:directoryManifest,uid:0,gid:0,mode:0o600,checksum:hash(directoryManifest)});
entries.sort((a,b)=>a.path.localeCompare(b.path));
const total=9+entries.reduce((sum,e)=>sum+2+encoder.encode(e.path).length+20+e.data.length,0);
const image=new Uint8Array(total),view=new DataView(image.buffer);image.set(encoder.encode("PCFD"));view.setUint8(4,1);view.setUint32(5,entries.length,true);let at=9;
for(const entry of entries){
  const name=encoder.encode(entry.path);view.setUint16(at,name.length,true);at+=2;image.set(name,at);at+=name.length;
  view.setUint32(at,entry.uid,true);view.setUint32(at+4,entry.gid,true);view.setUint32(at+8,entry.mode,true);
  view.setUint32(at+12,entry.data.length,true);view.setUint32(at+16,entry.checksum,true);at+=20;image.set(entry.data,at);at+=entry.data.length;
}
const installer=new Assembler().assembleBinary(fs.readFileSync(path.join(unix,"bin","installer.asm"),"utf8"));
const manifestOut={format:"PCFD",version:1,entries:entries.map(e=>({path:e.path,size:e.data.length,checksum:e.checksum,uid:e.uid,gid:e.gid,mode:e.mode})),requiredBytes:entries.reduce((sum,e)=>sum+e.data.length,0),bootFile:"kernel.bin"};
const outputs=[
  [path.join(build,"install.pcfd"),Buffer.from(image)],
  [path.join(build,"install.manifest.json"),Buffer.from(JSON.stringify(manifestOut,null,2)+"\n")],
  [path.join(build,"installer.bin"),Buffer.from(installer)],
  [path.join(root,"src","game","install-media.generated.js"),Buffer.from(`// Generated by scripts/build-unix-installer.mjs.\nexport const INSTALLER_BINARY=new Uint8Array(${JSON.stringify(Array.from(installer))});\nexport const INSTALL_PCFD_BASE64=${JSON.stringify(Buffer.from(image).toString("base64"))};\nexport const INSTALL_MANIFEST=${JSON.stringify(manifestOut)};\n`)]
];
let stale=false;for(const [file,data] of outputs){const old=fs.existsSync(file)?fs.readFileSync(file):null;if(!old||Buffer.compare(old,data)!==0)stale=true;}
if(check&&stale){console.error("Installer media is stale; run node scripts/build-unix-installer.mjs");process.exit(1);}
if(!check)for(const [file,data] of outputs){fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,data);}
console.log(check?"OK: installer media is current":`OK: built PCFD (${image.length} bytes, ${entries.length} files)`);
